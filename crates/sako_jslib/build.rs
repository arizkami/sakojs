//! Builds `bootstrap.js` from `js/*.js`.
//!
//! The files are fragments of one function body (they share a scope) and are
//! concatenated in file-name order inside the bootstrap wrapper. The runtime
//! loads the result as an external one-byte (Latin-1) V8 string, so any
//! non-ASCII character is written as a `\uXXXX` escape here; the sources can
//! use Unicode freely. Output: `$OUT_DIR/bootstrap.js`.

use std::fmt::Write as _;
use std::path::Path;

fn main() {
  let js_dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("js");
  println!("cargo:rerun-if-changed={}", js_dir.display());

  let mut files: Vec<_> = std::fs::read_dir(&js_dir)
    .expect("read js/")
    .map(|e| e.expect("read js/ entry").path())
    .filter(|p| p.extension().is_some_and(|e| e == "js"))
    .collect();
  files.sort();

  let mut out = String::from(
    "// Sako runtime bootstrap (generated by sako_jslib/build.rs from js/*.js).\n\
     // Evaluated once as a classic script; its completion value is a function\n\
     // that receives the native `ops` object and installs the global APIs.\n\
     (function bootstrap(ops) {\n",
  );
  for path in &files {
    println!("cargo:rerun-if-changed={}", path.display());
    let name = path.file_name().unwrap().to_string_lossy();
    let src = std::fs::read_to_string(path).unwrap_or_else(|e| panic!("read {name}: {e}"));
    let _ = writeln!(out, "// --- {name}");
    for c in src.chars() {
      if c.is_ascii() {
        out.push(c);
      } else {
        // Characters outside the BMP become a surrogate pair.
        let mut units = [0u16; 2];
        for u in c.encode_utf16(&mut units) {
          let _ = write!(out, "\\u{u:04x}");
        }
      }
    }
    if !src.ends_with('\n') {
      out.push('\n');
    }
  }
  out.push_str("})\n");

  let dest = Path::new(&std::env::var("OUT_DIR").unwrap()).join("bootstrap.js");
  std::fs::write(&dest, out).expect("write bootstrap.js");
}
